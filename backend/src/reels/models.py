"""Pydantic schemas and data contracts for Video System (Reels / Shorts)."""

from typing import List, Literal, Optional
from pydantic import BaseModel, Field


class WordTiming(BaseModel):
    """Timestamp for an individual word in the voiceover."""
    word: str
    start_ms: int = Field(ge=0, description="Start time in milliseconds")
    end_ms: int = Field(ge=0, description="End time in milliseconds")


class SceneSpec(BaseModel):
    """Specification of an individual scene/cut in the video."""
    scene_index: int = Field(ge=1, description="1-based scene index")
    role: Literal["hook", "problem", "solution", "explanation", "cta"] = Field(
        description="Role of the scene in the video flow"
    )
    narration: str = Field(min_length=5, description="Spoken voiceover text for this scene")
    search_keywords: List[str] = Field(
        min_length=1, max_length=5, description="Search queries for vertical B-Roll"
    )
    headline_overlay: str = Field(
        min_length=2, max_length=50, description="Short punchy headline overlay"
    )
    transition: Literal["fade", "crossfade", "none"] = Field(
        default="crossfade", description="Transition effect into next scene"
    )


class VideoScriptSchema(BaseModel):
    """Full script and storyboard generated by the scriptwriter."""
    topic: str = Field(min_length=3)
    target_duration_sec: int = Field(ge=15, le=60, default=30)
    bgm_mood: Literal["corporate_minimal", "energetic_tech", "inspiring_ambient", "dramatic_urgent"] = Field(
        default="corporate_minimal"
    )
    scenes: List[SceneSpec] = Field(min_length=2, max_length=8)


class VideoRunResult(BaseModel):
    """Result of the video pipeline generation."""
    ok: bool
    video_path: Optional[str] = None
    duration_sec: float = 0.0
    file_size_mb: float = 0.0
    scenes_count: int = 0
    issues: List[str] = Field(default_factory=list)
